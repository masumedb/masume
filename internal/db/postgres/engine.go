// postgresIncomparableTypes is the set of types without equality operators. jsonb supports equality.
var postgresIncomparableTypes = map[string]bool{"json": true, "xml": true}

// Dialect writes SQL the way every PostgreSQL-protocol server reads it.
var Dialect = &query.Dialect{
	Engine: core.EnginePostgres, Syntax: syntax.FlavourStandard, SchemaWord: "schema",
	StatementLanguage: "SQL", FenceTag: "sql", StatementHint: "select … from …",
	QuoteIdentifier: func(name string) string {
		return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
	},
	BuildPlaceholder: func(position int) string { return fmt.Sprintf("$%d", position) },
	CountExpression:  "count(*)::int8",
	RowLockClause:    " for update",
	// A backslash is a plain character in a Postgres literal, so only a quote is doubled.
	// PostgreSQL reads bytes as a string of the hexadecimal form.
	RenderBytes: func(hex string) string { return `'\x` + hex + `'` },
	RenderTime: func(held time.Time, dataType string) string {
		if strings.Contains(dataType, "with time zone") || dataType == "timestamptz" {
			return core.FormatZonedTime(held)
		}
		return core.FormatTimeLiteral(held, dataType)
	},
	MatchText: func(column, pattern string) string {
		return "cast(" + column + " as text) ilike " + pattern
	},
	QuoteTextLiteral: func(text string) string {
		return "'" + strings.ReplaceAll(text, "'", "''") + "'"
	},
	CanCompareType: func(dataType string) bool {
		return !postgresIncomparableTypes[query.ReadBaseType(dataType)]
	},
	ColumnTypes: map[core.ColumnKind]string{
		core.KindText: "text", core.KindInteger: "bigint", core.KindNumber: "numeric",
		core.KindBoolean: "boolean", core.KindTimestamp: "timestamptz",
	},
	IdentityColumn: "id bigserial primary key",
	ReadOnlyUnit:   query.ReadOnlyUnit{Open: "begin read only", Close: "commit"},
	// A GENERATED ALWAYS identity column takes a value of the client only with this clause.
	InsertOverride:          "overriding system value",
	IdentityClause:          "GENERATED ALWAYS AS IDENTITY",
	IdentityByDefaultClause: "GENERATED BY DEFAULT AS IDENTITY",
	RenderGeneratedColumn: func(expression string) string {
		return "GENERATED ALWAYS AS (" + expression + ") STORED"
	},
	DropSchema: func(dialect *query.Dialect, schema string) string {
		return "drop schema " + dialect.QuoteIdentifier(schema) + " restrict;"
	},
	RenderList: func(dialect *query.Dialect, elements []query.ListElement) string {
		return dialect.QuoteTextLiteral(buildArrayText(elements))
	},
	ListText: buildArrayText,
	DropTrigger: func(dialect *query.Dialect, schema, name, table string) string {
		target := dialect.BuildQualifiedName(query.QualifiedName{Schema: schema, Name: table})
		return "drop trigger " + dialect.QuoteIdentifier(name) + " on " + target + ";"
	},
	CreateIfMissing: func(
		dialect *query.Dialect, kind, schema, name string, lines []string,
	) []string {
		lookup := "to_regtype"
		if kind == string(db.ObjectSequence) {
			lookup = "to_regclass"
		}
		target := dialect.QuoteTextLiteral(
			dialect.BuildQualifiedName(query.QualifiedName{Schema: schema, Name: name}))
		guarded := []string{"DO $masume$ BEGIN IF " + lookup + "(" + target + ") IS NULL THEN"}
		for _, line := range lines {
			if strings.TrimSpace(line) != "" {
				guarded = append(guarded, line)
			}
		}
		if last := len(guarded) - 1; !strings.HasSuffix(strings.TrimSpace(guarded[last]), ";") {
			guarded[last] += ";"
		}
		return append(guarded, "END IF; END $masume$;")
	},
	// ROUTINE covers a function and a procedure. DROP FUNCTION refuses a procedure.
	DropRoutine: func(dialect *query.Dialect, schema, name, _ string) string {
		return "drop routine " +
			dialect.BuildQualifiedName(query.QualifiedName{Schema: schema, Name: name}) + ";"
	},
}

// Support is everything known about a PostgreSQL server before a connection exists.
var Support = db.EngineSupport{
	EngineInfo: core.ResolveEngineInfo(core.EnginePostgres),
	Dialect:    Dialect,
	Language:   language.SQL,
	Compose:    db.NewSQLComposer(Dialect),
}

// CockroachDialect is the PostgreSQL dialect with an IF NOT EXISTS guard. CockroachDB refuses
// a CREATE TYPE or a CREATE SEQUENCE inside a DO block.
var CockroachDialect = buildCockroachDialect()

// buildCockroachDialect returns a copy of the PostgreSQL dialect that guards a definition with
// CREATE TYPE IF NOT EXISTS or CREATE SEQUENCE IF NOT EXISTS.
func buildCockroachDialect() *query.Dialect {
	dialect := *Dialect
	dialect.CreateIfMissing = func(
		_ *query.Dialect, kind, _, _ string, lines []string,
	) []string {
		create := "CREATE " + strings.ToUpper(kind) + " "
		guarded := make([]string, 0, len(lines))
		for _, line := range lines {
			if rest, found := strings.CutPrefix(line, create); found {
				line = create + "IF NOT EXISTS " + rest
			}
			guarded = append(guarded, line)
		}
		return guarded
	}
	return &dialect
}

// BuildSupport combines engine metadata with the PostgreSQL dialect and language.
func BuildSupport(engine core.Engine) db.EngineSupport {
	dialect := Dialect
	if engine == core.EngineCockroach {
		dialect = CockroachDialect
	}
	return db.EngineSupport{
		EngineInfo: core.ResolveEngineInfo(engine),
		Dialect:    dialect,
		Language:   language.SQL,
		Compose:    db.NewSQLComposer(dialect),
	}
}

// buildArrayText writes a PostgreSQL array as `{…}`. Every element except a null is quoted,
// and a quote or a backslash inside it is escaped.
func buildArrayText(elements []query.ListElement) string {
	written := make([]string, 0, len(elements))
	for _, element := range elements {
		if element.IsNull {
			written = append(written, "NULL")
			continue
		}
		held := strings.ReplaceAll(element.Text, `\`, `\\`)
		written = append(written, `"`+strings.ReplaceAll(held, `"`, `\"`)+`"`)
	}
	return "{" + strings.Join(written, ",") + "}"
}

package dump_test

import (
	"context"
	"os"
	"strings"
	"testing"
	"time"

	"github.com/masumedb/masume/internal/db"
	"github.com/masumedb/masume/internal/db/dbtest"
	"github.com/masumedb/masume/internal/db/engines"
	"github.com/masumedb/masume/internal/dump"
)

const (
	cockroachSourceDatabase = "masume_cockroach_dump"
	cockroachCopyDatabase   = "masume_cockroach_copy"
)

var cockroachSchema = []string{
	"create type mood as enum ('happy', 'sad')",
	"create type address as (street string, city string)",
	"create sequence ticket_number",
	`create table customers (
  id      int primary key default nextval('ticket_number'),
  feeling mood,
  home    address,
  note    string
)`,
	"create table events (id int generated by default as identity primary key, label string)",
	`insert into customers (feeling, home, note)
  values ('happy', ('main', 'oslo'), 'first'), ('sad', null, 'a '';'' note')`,
	"insert into events (label) values ('one'), ('two'), ('three')",
}

var cockroachTables = []db.TableRef{
	{Schema: "public", Name: "customers", Kind: db.RelationTable},
	{Schema: "public", Name: "events", Kind: db.RelationTable},
}

// openCockroachDatabase creates a database that holds nothing and opens a session on it. The
// database is dropped when the test ends.
func openCockroachDatabase(t *testing.T, name string) db.Session {
	t.Helper()
	setup := dbtest.Open(t, dbtest.Cockroach)
	dbtest.RunStatements(t, setup,
		"drop database if exists "+name+" cascade", "create database "+name)
	t.Cleanup(func() {
		_, _ = setup.RunQuery(context.Background(),
			"drop database if exists "+name+" cascade", dbtest.ReadEverything, nil)
	})

	profile, password := dbtest.BuildProfile(t, dbtest.Cockroach)
	profile.Database = name
	ctx, stop := context.WithTimeout(context.Background(), 30*time.Second)
	defer stop()
	session, err := engines.CreateAdapters().Open(ctx, profile, password)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = session.Close() })
	return session
}

// openCockroachSource opens a database that holds the test schema.
func openCockroachSource(t *testing.T) db.Session {
	t.Helper()
	session := openCockroachDatabase(t, cockroachSourceDatabase)
	dbtest.RunStatements(t, session, cockroachSchema...)
	return session
}

// writeCockroachDump writes the dump and returns its path and its text without the lines
// that differ between two databases.
func writeCockroachDump(t *testing.T, session db.Session, options dump.Options) (string, string) {
	t.Helper()
	options.Schema = "public"
	path, _ := writeDump(t, session, options)
	written, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	kept := []string{}
	for line := range strings.SplitSeq(string(written), "\n") {
		if !strings.HasPrefix(line, "-- database: ") && !strings.HasPrefix(line, "-- written: ") {
			kept = append(kept, line)
		}
	}
	return path, strings.Join(kept, "\n")
}

// restoreCockroachDump runs the dump into the database of the session.
func restoreCockroachDump(t *testing.T, session db.Session, path string) {
	t.Helper()
	run, err := dump.RunFile(context.Background(), session, path, session.Dialect().Syntax)
	if err != nil {
		t.Fatalf("the restore answered %v after %d statements", err, run.Statements)
	}
}

// checkNextNumbers adds a row to each table and checks that it takes the number after the
// last restored row.
func checkNextNumbers(t *testing.T, session db.Session) {
	t.Helper()
	dbtest.RunStatements(t, session,
		"insert into customers (feeling, note) values ('sad', 'third')",
		"insert into events (label) values ('four')")
	for sql, wanted := range map[string]int64{
		"select max(id) from customers": 3,
		"select max(id) from events":    4,
	} {
		if held := readNumber(t, session, sql); held != wanted {
			t.Errorf("%s: %d, want %d", sql, held, wanted)
		}
	}
}

func TestCockroachDumpRestoresIntoAnEmptyDatabase(t *testing.T) {
	source := openCockroachSource(t)
	path, written := writeCockroachDump(t, source, dump.Options{Content: dump.ContentAll})
	for _, wanted := range []string{
		"CREATE TYPE public.mood AS ENUM ('happy', 'sad');",
		"CREATE TYPE public.address AS (street text, city text);",
		"SELECT pg_catalog.setval('public.ticket_number', 2, true);",
		"SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence('public.events', 'id'), 3, true);",
	} {
		if !strings.Contains(written, wanted) {
			t.Errorf("the dump holds no %q:\n%s", wanted, written)
		}
	}

	copied := openCockroachDatabase(t, cockroachCopyDatabase)
	restoreCockroachDump(t, copied, path)
	if _, again := writeCockroachDump(
		t, copied, dump.Options{Content: dump.ContentAll}); again != written {
		t.Errorf("the dump of the restored database differs:\n%s\nwant\n%s", again, written)
	}
	checkNextNumbers(t, copied)
}

func TestCockroachListsTheSequenceOfAnIdentityColumn(t *testing.T) {
	source := openCockroachSource(t)
	checkIdentitySequences(t, source, "public", map[string]bool{
		"events_id_seq": true,
		"ticket_number": false,
	})
}

func TestCockroachSchemaAndRowsDumpsRestoreIntoAnEmptyDatabase(t *testing.T) {
	source := openCockroachSource(t)
	schemaPath, schema := writeCockroachDump(t, source, dump.Options{Content: dump.ContentSchema})
	if !strings.Contains(schema, "CREATE TYPE public.mood AS ENUM ('happy', 'sad');") ||
		strings.Contains(schema, "insert into") || strings.Contains(schema, "setval") {
		t.Errorf("the schema dump wrote\n%s", schema)
	}
	rowsPath, rows := writeCockroachDump(t, source, dump.Options{Content: dump.ContentRows})
	if strings.Contains(rows, "CREATE") || !strings.Contains(rows, "a '';'' note") ||
		!strings.Contains(rows, "'public.ticket_number', 2, true") {
		t.Errorf("the rows dump wrote\n%s", rows)
	}

	copied := openCockroachDatabase(t, cockroachCopyDatabase)
	restoreCockroachDump(t, copied, schemaPath)
	restoreCockroachDump(t, copied, rowsPath)
	_, written := writeCockroachDump(t, source, dump.Options{Content: dump.ContentAll})
	if _, again := writeCockroachDump(
		t, copied, dump.Options{Content: dump.ContentAll}); again != written {
		t.Errorf("the dump of the restored database differs:\n%s\nwant\n%s", again, written)
	}
	checkNextNumbers(t, copied)
}

// A dump of named tables creates the types and the sequences they use only where they are
// missing, so it runs twice into the same database.
func TestCockroachTableDumpRestoresIntoAnEmptyDatabase(t *testing.T) {
	source := openCockroachSource(t)
	options := dump.Options{Content: dump.ContentAll, DropsFirst: true, Tables: cockroachTables}
	path, written := writeCockroachDump(t, source, options)

	copied := openCockroachDatabase(t, cockroachCopyDatabase)
	restoreCockroachDump(t, copied, path)
	restoreCockroachDump(t, copied, path)
	if _, again := writeCockroachDump(t, copied, options); again != written {
		t.Errorf("the dump of the restored tables differs:\n%s\nwant\n%s", again, written)
	}
	checkNextNumbers(t, copied)
}
